import AppKit
import CopierCore
import UniformTypeIdentifiers

/// The Mac clipboard, in the shapes the protocol sends.
enum LocalClip {
    case text(String, html: Data?, sensitive: Bool)
    case image(Data, mime: String, sensitive: Bool)
    case files([URL])
}

/// Watches and writes the general pasteboard.
@MainActor
final class PasteboardSync {
    enum Access {
        case allowed, notYetAsked, ask, denied
    }

    static let remoteMarker = NSPasteboard.PasteboardType(Proto.remoteClipMarker)
    // nspasteboard.org conventions used by password managers and clipboard tools.
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let jpeg = NSPasteboard.PasteboardType(UTType.jpeg.identifier)

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    var onLocalChange: @MainActor (LocalClip) -> Void = { _ in }
    var onAccessBlocked: @MainActor () -> Void = {}

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        // macOS has no pasteboard-changed notification. Reading changeCount is a cheap integer
        // read that never touches contents, so it doesn't trigger the privacy prompt.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// macOS 15.4+ asks the user before an app reads the clipboard in the background unless the
    /// app is set to "Always Allow" in Privacy & Security → Paste from Other Apps.
    var access: Access {
        guard #available(macOS 15.4, *) else { return .allowed }
        switch pasteboard.accessBehavior {
        case .alwaysAllow: return .allowed
        case .default: return .notYetAsked
        case .alwaysDeny: return .denied
        case .ask: return .ask
        @unknown default: return .ask
        }
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        // In "ask" mode every read would pop an alert, so auto-sync waits for "Always Allow".
        // "notYetAsked" reads once on purpose: that first prompt is what lists the app in Settings.
        guard access == .allowed || access == .notYetAsked else {
            Log.clip.info("clipboard changed but access is not Always Allow; skipping")
            onAccessBlocked()
            return
        }
        if let clip = read() { onLocalChange(clip) }
    }

    /// Reads the current clipboard, or nil for empty, unsupported, transient or our own writes.
    func read() -> LocalClip? {
        let types = pasteboard.types ?? []
        if types.contains(Self.remoteMarker) || types.contains(Self.transient) || types.contains(Self.autoGenerated) {
            return nil
        }
        let sensitive = types.contains(Self.concealed)
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        // Image first only when it is the primary flavor; a copied web snippet also carries
        // images, but the user meant the text.
        if let first = types.first, Self.isImage(first), let image = imageData() {
            return .image(image.data, mime: image.mime, sensitive: sensitive)
        }
        if let text = pasteboard.string(forType: .string) {
            return .text(text, html: pasteboard.data(forType: .html), sensitive: sensitive)
        }
        if let image = imageData() {
            return .image(image.data, mime: image.mime, sensitive: sensitive)
        }
        return nil
    }

    func apply(text: String, html: Data?, sensitive: Bool) {
        write(sensitive: sensitive) { item in
            item.setString(text, forType: .string)
            if let html { item.setData(html, forType: .html) }
        }
    }

    func apply(image: Data, mime: String, sensitive: Bool) {
        let type: NSPasteboard.PasteboardType
        var data = image
        switch mime {
        case "image/png": type = .png
        case "image/jpeg": type = Self.jpeg
        default:
            // WebP/GIF/HEIC paste poorly in many Mac apps; ImageIO can decode them, so ship PNG.
            guard let png = NSBitmapImageRep(data: image)?.representation(using: .png, properties: [:]) else {
                Log.clip.error("could not decode received \(mime, privacy: .public) image")
                return
            }
            type = .png
            data = png
        }
        write(sensitive: sensitive) { $0.setData(data, forType: type) }
    }

    /// Puts a file on the clipboard the way Finder does, so ⌘V in Finder or Mail pastes the file.
    func apply(fileURL: URL) {
        write(sensitive: false) { $0.setString(fileURL.absoluteString, forType: .fileURL) }
    }

    private func write(sensitive: Bool, _ fill: (NSPasteboardItem) -> Void) {
        let item = NSPasteboardItem()
        fill(item)
        item.setData(Data(), forType: Self.remoteMarker)
        if sensitive { item.setData(Data(), forType: Self.concealed) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        lastChangeCount = pasteboard.changeCount  // never echo our own write back to the phone
    }

    private func imageData() -> (data: Data, mime: String)? {
        if let png = pasteboard.data(forType: .png) { return (png, "image/png") }
        if let jpeg = pasteboard.data(forType: Self.jpeg) { return (jpeg, "image/jpeg") }
        if let tiff = pasteboard.data(forType: .tiff),
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            return (png, "image/png")
        }
        return nil
    }

    private static func isImage(_ type: NSPasteboard.PasteboardType) -> Bool {
        UTType(type.rawValue)?.conforms(to: .image) == true
    }
}
